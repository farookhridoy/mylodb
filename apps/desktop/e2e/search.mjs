// Data search: search a database, see the matching tables and columns, open a table filtered to the matching column.
import { chromium } from "playwright-core";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.addInitScript({ content: fs.readFileSync(new URL("./mock.js", import.meta.url), "utf8") + "\nSIZES.orders = 900 * 1024 * 1024; // orders is the biggest table here" });
await page.goto(process.env.APP_URL || "http://localhost:1420/");
let step = 0;
const ok = (m) => console.log(`ok ${++step} ${m}`);
await page.selectOption(".conn-bar select", "1");
await page.selectOption(".conn-bar select", "1");
await page.waitForSelector(".tree .db");
await page.click(".tree .db:has-text('shop')", { button: "right" });
await page.getByText("Search data…").click();
await page.waitForSelector("h2:has-text('Data search')");
const go = page.locator("button:text-is('Search')");
assert.equal(await go.isDisabled(), true, "a search text is required");
await page.fill("input[placeholder='text or number']", "ann@example.com");
await page.click("label:has-text('Whole value') input");
await page.click("label:has-text('Also numbers') input");
await go.click();
await page.waitForSelector("table[aria-label=Matches]");
const call = await page.evaluate(() => window.__calls.filter((c) => c.cmd === "search_data").at(-1).args);
assert.deepEqual([call.id, call.db, call.request], [1, "shop", { needle: "ann@example.com", exact: true, all_columns: true }]);
assert.match(call.jobId, /^search-/);
assert.match(await page.locator("p[aria-label=Summary]").innerText(), /found in 2 of 4 tables of shop/);
const rows = await page.locator("table[aria-label=Matches] tbody tr").allInnerTexts();
assert.equal(rows.length, 2);
assert.match(rows[0], /customers\s+2\s+email\s+\(2\)\s+note\s+\(1\)/);
await page.locator("summary:has-text('not searched')").click();
assert.match(await page.locator("details").innerText(), /blobs: no text column/);
ok("a search sends the text and options, lists the matching tables with per-column counts, and says what it skipped");

await page.click("tr:has-text('customers') button:has-text('email')");
await page.waitForSelector(".dg, table.dg", { timeout: 5000 }).catch(() => {});
const tab = await page.locator(".qtab.active").innerText();
assert.match(tab, /customers/);
ok("a column in the results opens that table (filtered to the match)");
assert.deepEqual(errors, []);
await browser.close();
console.log("ALL DATA SEARCH UI CHECKS PASSED");
