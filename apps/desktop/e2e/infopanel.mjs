// Info tab of the results pane: facts about the object selected in the tree (the sidebar stays for the tree).
import { chromium } from "playwright-core";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.addInitScript({ content: fs.readFileSync(new URL("./mock.js", import.meta.url), "utf8") + "\nSIZES.orders = 900 * 1024 * 1024; // orders is the biggest table here" });
await page.goto(process.env.APP_URL || "http://localhost:1420/");
let step = 0;
const ok = (m) => console.log(`ok ${++step} ${m}`);
await page.selectOption(".conn-bar select", "1");
await page.waitForSelector(".tree .db");
assert.equal(await page.locator(".object-info").count(), 0, "the sidebar keeps its space for the tree");
await page.click("button[role=tab]:has-text('Info'), .rtabs button:has-text('Info'), button:has-text('Info')");
const info = page.locator(".info-pane");
assert.match(await info.innerText(), /Select a database or table in the tree/);
await page.click(".tree .db:has-text('shop')");
await page.waitForFunction(() => /Tables\s+2/.test(document.querySelector(".info-pane")?.innerText ?? ""));
assert.match(await info.innerText(), /selected in the tree: shop/i);
ok("the Info tab shows the object counts of the selected database");
await page.click(".row-item.leaf:has-text('customers')");
await page.waitForFunction(() => /Engine/.test(document.querySelector(".info-pane")?.innerText ?? ""));
assert.match(await info.innerText(), /shop\.customers/i);
ok("and the engine, rows, size and columns of the selected table");
assert.deepEqual(errors, []);
await browser.close();
console.log("ALL INFO PANEL UI CHECKS PASSED");
