//! Staged edits applied atomically. Rows are identified by the table's `row_key`, never by position.

use crate::{meta::{ColumnMeta, TableMeta}, q, Error, Result};
use myq_driver::mysql_async::{prelude::Queryable, TxOpts, Value};
use myq_driver::{hex, Conn};
use serde::{Deserialize, Serialize};

/// A cell value chosen by the user. `Text` on a binary column may be `0x…` hex.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
#[serde(tag = "kind", content = "value", rename_all = "snake_case")]
pub enum CellValue {
    Null,
    Default,
    Text(String),
    /// Read the file's bytes at apply time (upload into a BLOB).
    File(String),
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct Assign {
    pub column: String,
    pub value: CellValue,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
#[serde(tag = "op", rename_all = "snake_case")]
pub enum Change {
    /// `key` is the row's original `row_key` values.
    Update { key: Vec<Assign>, set: Vec<Assign> },
    Insert { values: Vec<Assign> },
    Delete { key: Vec<Assign> },
}

#[derive(Debug, Serialize)]
pub struct ApplyOutcome {
    pub applied: usize,
    /// Auto-increment id generated by each insert, in order.
    pub insert_ids: Vec<u64>,
}

/// A statement as text fragments and bound values, so it can be run with `?` placeholders
/// or rendered with literals for preview from the same source.
enum Piece {
    Sql(String),
    Param { value: Value, preview: String },
}

struct Stmt(Vec<Piece>);

impl Stmt {
    fn sql(&self) -> String {
        self.0.iter().map(|p| match p { Piece::Sql(s) => s.as_str(), Piece::Param { .. } => "?" }).collect()
    }
    fn params(&self) -> Vec<Value> {
        self.0.iter().filter_map(|p| match p { Piece::Param { value, .. } => Some(value.clone()), _ => None }).collect()
    }
    fn preview(&self) -> String {
        self.0.iter().map(|p| match p { Piece::Sql(s) => s.clone(), Piece::Param { preview, .. } => preview.clone() }).collect()
    }
}

fn sql(s: impl Into<String>) -> Piece {
    Piece::Sql(s.into())
}

/// Bytes for a text value written to a binary column: `0x…` hex, otherwise the UTF-8 bytes.
fn text_bytes(col: &ColumnMeta, t: &str) -> Vec<u8> {
    if col.binary {
        if let Some(h) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
            if h.len() % 2 == 0 && h.chars().all(|c| c.is_ascii_hexdigit()) {
                return (0..h.len()).step_by(2).map(|i| u8::from_str_radix(&h[i..i + 2], 16).unwrap()).collect();
            }
        }
    }
    t.as_bytes().to_vec()
}

/// `None` = the `DEFAULT` keyword.
fn value_piece(col: &ColumnMeta, v: &CellValue) -> Result<Piece> {
    Ok(match v {
        CellValue::Default => sql("DEFAULT"),
        CellValue::Null => Piece::Param { value: Value::NULL, preview: "NULL".into() },
        CellValue::Text(t) if col.binary => {
            let b = text_bytes(col, t);
            Piece::Param { preview: format!("X'{}'", hex(&b)), value: Value::Bytes(b) }
        }
        CellValue::Text(t) => Piece::Param { value: Value::Bytes(t.as_bytes().to_vec()), preview: format!("'{}'", t.replace('\\', "\\\\").replace('\'', "''")) },
        CellValue::File(path) => {
            let b = std::fs::read(path)?;
            Piece::Param { preview: format!("<{} bytes from {path}>", b.len()), value: Value::Bytes(b) }
        }
    })
}

fn writable<'a>(meta: &'a TableMeta, name: &str) -> Result<&'a ColumnMeta> {
    let c = meta.column(name)?;
    if c.generated {
        return Err(Error::NotEditable(format!("column `{name}` is generated")));
    }
    Ok(c)
}

/// WHERE for the row key. The supplied key must name exactly the table's `row_key` columns.
fn key_where(meta: &TableMeta, key: &[Assign]) -> Result<Vec<Piece>> {
    if let Some(reason) = &meta.read_only_reason {
        return Err(Error::NotEditable(reason.clone()));
    }
    let mut names: Vec<&str> = key.iter().map(|k| k.column.as_str()).collect();
    let mut want: Vec<&str> = meta.row_key.iter().map(String::as_str).collect();
    names.sort_unstable();
    want.sort_unstable();
    if names != want {
        return Err(Error::Invalid(format!("row key must be exactly ({})", meta.row_key.join(", "))));
    }
    let mut out = vec![sql(" WHERE ")];
    for (i, k) in key.iter().enumerate() {
        if i > 0 {
            out.push(sql(" AND "));
        }
        if matches!(k.value, CellValue::Null | CellValue::Default) {
            return Err(Error::Invalid(format!("key column `{}` has no value", k.column)));
        }
        out.push(sql(format!("{} = ", q(&k.column))));
        out.push(value_piece(meta.column(&k.column)?, &k.value)?);
    }
    Ok(out)
}

fn build(meta: &TableMeta, change: &Change) -> Result<Stmt> {
    let mut p = Vec::new();
    match change {
        Change::Update { key, set } => {
            if set.is_empty() {
                return Err(Error::Invalid("update changes no columns".into()));
            }
            p.push(sql(format!("UPDATE {} SET ", meta.qualified())));
            for (i, a) in set.iter().enumerate() {
                if i > 0 {
                    p.push(sql(", "));
                }
                p.push(sql(format!("{} = ", q(&a.column))));
                p.push(value_piece(writable(meta, &a.column)?, &a.value)?);
            }
            p.extend(key_where(meta, key)?);
            p.push(sql(" LIMIT 1"));
        }
        Change::Insert { values } => {
            if meta.is_view {
                return Err(Error::NotEditable("views are read-only".into()));
            }
            if values.is_empty() {
                p.push(sql(format!("INSERT INTO {} () VALUES ()", meta.qualified())));
            } else {
                let cols: Vec<String> = values.iter().map(|a| q(&a.column)).collect();
                p.push(sql(format!("INSERT INTO {} ({}) VALUES (", meta.qualified(), cols.join(", "))));
                for (i, a) in values.iter().enumerate() {
                    if i > 0 {
                        p.push(sql(", "));
                    }
                    p.push(value_piece(writable(meta, &a.column)?, &a.value)?);
                }
                p.push(sql(")"));
            }
        }
        Change::Delete { key } => {
            p.push(sql(format!("DELETE FROM {}", meta.qualified())));
            p.extend(key_where(meta, key)?);
            p.push(sql(" LIMIT 1"));
        }
    }
    Ok(Stmt(p))
}

/// The SQL that `apply_changes` would run, with values rendered as literals.
pub fn preview_changes(meta: &TableMeta, changes: &[Change]) -> Result<Vec<String>> {
    changes.iter().enumerate().map(|(i, c)| build(meta, c).map(|s| s.preview()).map_err(|e| at(i, e))).collect()
}

fn at(index: usize, e: Error) -> Error {
    Error::Change { index, message: e.to_string() }
}

/// Run all changes in one transaction; any failure rolls everything back.
pub async fn apply_changes(conn: &mut Conn, meta: &TableMeta, changes: &[Change]) -> Result<ApplyOutcome> {
    // Build everything first so validation errors never leave a half-open transaction.
    let stmts: Vec<Stmt> = changes.iter().enumerate().map(|(i, c)| build(meta, c).map_err(|e| at(i, e))).collect::<Result<_>>()?;
    let mut tx = conn.start_transaction(TxOpts::default()).await?;
    let mut insert_ids = Vec::new();
    for (i, (change, stmt)) in changes.iter().zip(&stmts).enumerate() {
        let run: Result<()> = async {
            tx.exec_drop(stmt.sql(), stmt.params()).await?;
            match change {
                Change::Insert { .. } => insert_ids.push(tx.last_insert_id().unwrap_or(0)),
                // 0 affected rows means either "unchanged" or "gone"; only the latter is an error.
                Change::Update { key, .. } | Change::Delete { key } if tx.affected_rows() == 0 => {
                    let mut check = vec![sql(format!("SELECT 1 FROM {}", meta.qualified()))];
                    check.extend(key_where(meta, key)?);
                    let check = Stmt(check);
                    let exists: Option<u8> = tx.exec_first(check.sql(), check.params()).await?;
                    if exists.is_none() {
                        return Err(Error::Invalid("row no longer exists (changed by someone else?)".into()));
                    }
                }
                _ => {}
            }
            Ok(())
        }
        .await;
        if let Err(e) = run {
            let _ = tx.rollback().await;
            return Err(at(i, e));
        }
    }
    tx.commit().await?;
    Ok(ApplyOutcome { applied: changes.len(), insert_ids })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, binary: bool, generated: bool) -> ColumnMeta {
        ColumnMeta {
            name: name.into(), data_type: if binary { "blob" } else { "varchar" }.into(), column_type: String::new(), nullable: true,
            key: String::new(), default: None, extra: String::new(), comment: String::new(), binary, generated, auto_increment: false,
        }
    }

    fn meta(row_key: &[&str]) -> TableMeta {
        TableMeta {
            database: "d".into(), table: "t".into(), is_view: false,
            columns: vec![col("id", false, false), col("name", false, false), col("img", true, false), col("gen", false, true)],
            primary_key: row_key.iter().map(|s| s.to_string()).collect(), row_key: row_key.iter().map(|s| s.to_string()).collect(),
            foreign_keys: vec![], read_only_reason: if row_key.is_empty() { Some("no key".into()) } else { None },
        }
    }

    fn a(c: &str, v: CellValue) -> Assign {
        Assign { column: c.into(), value: v }
    }
    fn t(s: &str) -> CellValue {
        CellValue::Text(s.into())
    }

    #[test]
    fn preview_renders_each_kind_of_change() {
        let m = meta(&["id"]);
        let out = preview_changes(&m, &[
            Change::Update { key: vec![a("id", t("7"))], set: vec![a("name", t("O'Neil\\x")), a("img", t("0xCAFE")), a("id", CellValue::Default)] },
            Change::Insert { values: vec![a("name", CellValue::Null)] },
            Change::Insert { values: vec![] },
            Change::Delete { key: vec![a("id", t("7"))] },
        ]).unwrap();
        assert_eq!(out[0], "UPDATE `d`.`t` SET `name` = 'O''Neil\\\\x', `img` = X'CAFE', `id` = DEFAULT WHERE `id` = '7' LIMIT 1");
        assert_eq!(out[1], "INSERT INTO `d`.`t` (`name`) VALUES (NULL)");
        assert_eq!(out[2], "INSERT INTO `d`.`t` () VALUES ()");
        assert_eq!(out[3], "DELETE FROM `d`.`t` WHERE `id` = '7' LIMIT 1");
    }

    #[test]
    fn placeholders_and_params_line_up() {
        let m = meta(&["id"]);
        let s = build(&m, &Change::Update { key: vec![a("id", t("1"))], set: vec![a("name", t("x")), a("id", CellValue::Default)] }).unwrap();
        assert_eq!(s.sql(), "UPDATE `d`.`t` SET `name` = ?, `id` = DEFAULT WHERE `id` = ? LIMIT 1");
        assert_eq!(s.params().len(), 2);
    }

    #[test]
    fn refuses_unsafe_changes() {
        let m = meta(&["id"]);
        // wrong / partial key
        assert!(matches!(build(&m, &Change::Delete { key: vec![a("name", t("x"))] }), Err(Error::Invalid(_))));
        assert!(matches!(build(&m, &Change::Delete { key: vec![] }), Err(Error::Invalid(_))));
        // NULL key
        assert!(build(&m, &Change::Delete { key: vec![a("id", CellValue::Null)] }).is_err());
        // generated column, unknown column, empty update
        assert!(matches!(build(&m, &Change::Insert { values: vec![a("gen", t("x"))] }), Err(Error::NotEditable(_))));
        assert!(matches!(build(&m, &Change::Insert { values: vec![a("zzz", t("x"))] }), Err(Error::UnknownColumn(_))));
        assert!(build(&m, &Change::Update { key: vec![a("id", t("1"))], set: vec![] }).is_err());
        // no key => read-only
        let ro = meta(&[]);
        assert!(matches!(build(&ro, &Change::Delete { key: vec![a("id", t("1"))] }), Err(Error::NotEditable(_))));
    }

    #[test]
    fn invalid_hex_on_binary_column_is_stored_as_text() {
        let c = col("img", true, false);
        assert_eq!(text_bytes(&c, "0xZZ"), b"0xZZ");
        assert_eq!(text_bytes(&c, "0x0aFF"), vec![0x0A, 0xFF]);
        assert_eq!(text_bytes(&col("n", false, false), "0xCAFE"), b"0xCAFE", "hex only applies to binary columns");
    }
}
