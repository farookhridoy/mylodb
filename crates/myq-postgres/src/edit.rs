//! Staged grid edits for a PostgreSQL table, applied in one transaction. The same `myq_data::Change` the MySQL path takes; every
//! update and delete must change exactly the one row its key names.

use crate::backend::{explain, PgBackend};
use crate::grid::{params, q, read_meta, PgMeta};
use myq_core::{Dialect, Postgres};
use myq_data::{ApplyOutcome, Assign, CellValue, Change};

type Result<T> = std::result::Result<T, String>;

/// A statement twice over, built together: with `$n` placeholders to run, and with literals to show.
#[derive(Default)]
struct Stmt {
    sql: String,
    preview: String,
    values: Vec<String>,
}

impl Stmt {
    fn push(&mut self, text: impl AsRef<str>) {
        self.sql.push_str(text.as_ref());
        self.preview.push_str(text.as_ref());
    }

    fn value(&mut self, m: &PgMeta, column: &str, v: &CellValue) -> Result<()> {
        let col = m.column(column)?;
        match v {
            CellValue::Null => self.push("NULL"),
            CellValue::Default => self.push("DEFAULT"),
            // bytea travels as hex digits: `0x…` typed by the user, the bytes of any other text, or a file
            CellValue::Text(t) if col.binary => {
                let typed = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")).filter(|h| h.len() % 2 == 0 && h.chars().all(|c| c.is_ascii_hexdigit()));
                let hex = typed.map(str::to_string).unwrap_or_else(|| hex(t.as_bytes()));
                self.preview.push_str(&format!("'\\x{hex}'"));
                self.values.push(hex);
                self.sql.push_str(&format!("decode(${}::text, 'hex')", self.values.len()));
            }
            CellValue::Text(t) => {
                self.preview.push_str(&Postgres.quote_string(t));
                self.values.push(t.clone());
                self.sql.push_str(&m.typed(column, self.values.len()));
            }
            CellValue::File(path) => {
                let bytes = std::fs::read(path).map_err(|e| format!("cannot read {path}: {e}"))?;
                self.preview.push_str(&format!("<{} bytes from {path}>", bytes.len()));
                if col.binary {
                    self.values.push(hex(&bytes));
                    self.sql.push_str(&format!("decode(${}::text, 'hex')", self.values.len()));
                } else {
                    self.values.push(String::from_utf8(bytes).map_err(|_| format!("{path} is not text, and column `{column}` is not binary"))?);
                    self.sql.push_str(&m.typed(column, self.values.len()));
                }
            }
        }
        Ok(())
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02X}")).collect()
}

fn writable(m: &PgMeta, name: &str) -> Result<()> {
    if m.column(name)?.generated {
        return Err(format!("column `{name}` is generated by the server"));
    }
    Ok(())
}

/// WHERE for the row key. The supplied key must name exactly the table's `row_key` columns.
fn key_where(s: &mut Stmt, m: &PgMeta, key: &[Assign]) -> Result<()> {
    let mut names: Vec<&str> = key.iter().map(|k| k.column.as_str()).collect();
    let mut want: Vec<&str> = m.meta.row_key.iter().map(String::as_str).collect();
    names.sort_unstable();
    want.sort_unstable();
    if names != want {
        return Err(format!("row key must be exactly ({})", m.meta.row_key.join(", ")));
    }
    s.push(" WHERE ");
    for (i, k) in key.iter().enumerate() {
        if i > 0 {
            s.push(" AND ");
        }
        if matches!(k.value, CellValue::Null | CellValue::Default) {
            return Err(format!("key column `{}` has no value", k.column));
        }
        s.push(format!("{} = ", q(&k.column)));
        s.value(m, &k.column, &k.value)?;
    }
    Ok(())
}

fn build(m: &PgMeta, change: &Change) -> Result<Stmt> {
    if let Some(reason) = &m.meta.read_only_reason {
        return Err(format!("cannot change rows: {reason}"));
    }
    let table = m.qualified();
    let mut s = Stmt::default();
    match change {
        Change::Update { key, set } => {
            if set.is_empty() {
                return Err("update changes no columns".into());
            }
            s.push(format!("UPDATE {table} SET "));
            for (i, a) in set.iter().enumerate() {
                if i > 0 {
                    s.push(", ");
                }
                writable(m, &a.column)?;
                s.push(format!("{} = ", q(&a.column)));
                s.value(m, &a.column, &a.value)?;
            }
            key_where(&mut s, m, key)?;
        }
        Change::Insert { values } => {
            // a column left at DEFAULT is simply not named
            let mut named = Vec::new();
            for a in values {
                if a.value != CellValue::Default {
                    writable(m, &a.column)?;
                    named.push(a);
                }
            }
            if named.is_empty() {
                s.push(format!("INSERT INTO {table} DEFAULT VALUES"));
            } else {
                let cols: Vec<String> = named.iter().map(|a| q(&a.column)).collect();
                s.push(format!("INSERT INTO {table} ({}) VALUES (", cols.join(", ")));
                for (i, a) in named.iter().enumerate() {
                    if i > 0 {
                        s.push(", ");
                    }
                    s.value(m, &a.column, &a.value)?;
                }
                s.push(")");
            }
        }
        Change::Delete { key } => {
            s.push(format!("DELETE FROM {table}"));
            key_where(&mut s, m, key)?;
        }
    }
    Ok(s)
}

fn at(index: usize, message: String) -> String {
    format!("change {}: {message}", index + 1)
}

fn build_all(m: &PgMeta, changes: &[Change]) -> Result<Vec<Stmt>> {
    changes.iter().enumerate().map(|(i, c)| build(m, c).map_err(|e| at(i, e))).collect()
}

/// The SQL that `apply_changes` would run, with values rendered as literals.
pub fn preview_changes(m: &PgMeta, changes: &[Change]) -> Result<Vec<String>> {
    Ok(build_all(m, changes)?.into_iter().map(|s| s.preview).collect())
}

/// Run all changes in one transaction; any failure rolls everything back. Returns the outcome and the statements that ran, for the
/// history. `insert_ids` holds the number of each inserted row when its key is one whole number, otherwise 0.
pub async fn apply_changes(b: &PgBackend, schema: &str, table: &str, changes: &[Change]) -> Result<(ApplyOutcome, Vec<String>)> {
    if b.read_only() {
        return Err("cannot change rows: this connection is read-only".into());
    }
    let client = b.checkout().await.map_err(|e| e.0)?;
    let outcome = async {
        let m = read_meta(&client, schema, table, true).await?;
        // everything is built first, so a validation error never opens a transaction
        let stmts = build_all(&m, changes)?;
        client.batch_execute("BEGIN").await.map_err(|e| explain(e).0)?;
        let mut insert_ids = Vec::new();
        for (i, (change, s)) in changes.iter().zip(&stmts).enumerate() {
            let fail = |e: tokio_postgres::Error| at(i, explain(e).0);
            if matches!(change, Change::Insert { .. }) {
                let returning = match m.meta.primary_key.as_slice() {
                    [one] => format!(" RETURNING {}::text", q(one)),
                    _ => " RETURNING NULL::text".to_string(),
                };
                let row = client.query_opt(&format!("{}{returning}", s.sql), &params(&s.values)).await.map_err(fail)?;
                let row = row.ok_or_else(|| at(i, "the row was not inserted (a trigger or rule refused it)".into()))?;
                insert_ids.push(row.get::<_, Option<String>>(0).and_then(|v| v.parse().ok()).unwrap_or(0));
            } else {
                match client.execute(&s.sql, &params(&s.values)).await.map_err(fail)? {
                    1 => {}
                    0 => return Err(at(i, "row no longer exists (changed by someone else?)".into())),
                    n => return Err(at(i, format!("the key matches {n} rows, so nothing was changed"))),
                }
            }
        }
        // a deferred constraint fails here
        client.batch_execute("COMMIT").await.map_err(|e| explain(e).0)?;
        Ok((ApplyOutcome { applied: changes.len(), insert_ids }, stmts.into_iter().map(|s| s.preview).collect()))
    }
    .await;
    // rolls back whatever was not committed
    b.give_back(client).await;
    outcome
}
