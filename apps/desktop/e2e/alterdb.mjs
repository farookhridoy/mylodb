// Alter database from the tree menu: pick a collation, review the SQL.
import { chromium } from "playwright-core";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.addInitScript({ content: fs.readFileSync(new URL("./mock.js", import.meta.url), "utf8") + "\nSIZES.orders = 900 * 1024 * 1024; // orders is the biggest table here" });
await page.goto(process.env.APP_URL || "http://localhost:1420/");
let step = 0;
const ok = (m) => console.log(`ok ${++step} ${m}`);
await page.selectOption(".conn-bar select", "1");
await page.selectOption(".conn-bar select", "1");
await page.waitForSelector(".tree .db");
await page.click(".tree .db:has-text('shop')", { button: "right" });
await page.click(".ctx-menu >> text=Alter database…").catch(async () => { await page.getByText("Alter database…").click(); });
await page.waitForSelector("[aria-label='Alter database']");
assert.equal(await page.locator("[aria-label='Alter database'] .primary").isDisabled(), true, "no collation chosen yet");
await page.click("[aria-label='Alter database'] .ss-trigger");
await page.click(".ss-opt:has-text('utf8mb4_bin')");
await page.click("[aria-label='Alter database'] .primary");
await page.waitForSelector("text=ALTER DATABASE `shop` COLLATE utf8mb4_bin;");
const plans = await page.evaluate(() => window.__plans);
assert.deepEqual(plans.at(-1), { op: "alter_database", name: "shop", charset: null, collation: "utf8mb4_bin" });
ok("Alter database picks a collation and shows the ALTER DATABASE statement in Preview SQL");
assert.deepEqual(errors, []);
await browser.close();
console.log("ALL ALTER DATABASE UI CHECKS PASSED");
