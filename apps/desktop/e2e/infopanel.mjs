// Info panel under the tree: facts about the selected database or table; collapsible and remembered.
import { chromium } from "playwright-core";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.addInitScript({ content: fs.readFileSync(new URL("./mock.js", import.meta.url), "utf8") + "\nSIZES.orders = 900 * 1024 * 1024; // orders is the biggest table here" });
await page.goto(process.env.APP_URL || "http://localhost:1420/");
let step = 0;
const ok = (m) => console.log(`ok ${++step} ${m}`);
await page.selectOption(".conn-bar select", "1");
await page.selectOption(".conn-bar select", "1");
await page.waitForSelector(".tree .db");
const panel = page.locator(".object-info");
assert.match(await panel.innerText(), /Select a database or table/);
await page.click(".tree .db:has-text('shop')");
await page.waitForFunction(() => /Tables/.test(document.querySelector(".object-info")?.innerText ?? ""));
const dbText = await panel.innerText();
assert.match(dbText, /shop/);
assert.match(dbText, /Tables\s+2/);
ok("a selected database shows its object counts");
await page.click(".row-item.leaf:has-text('customers')");
await page.waitForFunction(() => /Engine/.test(document.querySelector(".object-info")?.innerText ?? ""));
assert.match(await panel.innerText(), /shop\.customers/);
ok("a selected table shows engine, rows, size and columns");
await page.click(".object-info-head");
assert.doesNotMatch(await panel.innerText(), /Engine/);
assert.equal(await page.evaluate(() => localStorage.getItem("mylodb.infoPanel")), "closed");
ok("the panel collapses and remembers it");
assert.deepEqual(errors, []);
await browser.close();
console.log("ALL INFO PANEL UI CHECKS PASSED");
