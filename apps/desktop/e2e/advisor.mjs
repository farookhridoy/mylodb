// Index advisor: findings with their SQL, drops pre-selected, a missing foreign key index is not, apply through Preview SQL.
import { chromium } from "playwright-core";
import fs from "node:fs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.addInitScript({ content: fs.readFileSync(new URL("./mock.js", import.meta.url), "utf8") + "\nSIZES.orders = 900 * 1024 * 1024; // orders is the biggest table here" });
await page.goto(process.env.APP_URL || "http://localhost:1420/");
let step = 0;
const ok = (m) => console.log(`ok ${++step} ${m}`);
await page.selectOption(".conn-bar select", "1");
await page.selectOption(".conn-bar select", "1");
await page.waitForSelector(".tree .db");
await page.click(".tree .db:has-text('shop')", { button: "right" });
await page.getByText("Index advisor…").click();
await page.waitForSelector("table[aria-label=Findings]");
assert.match(await page.locator("p[aria-label=Summary]").innerText(), /3 findings in 3 tables/);
const call = await page.evaluate(() => window.__calls.filter((c) => c.cmd === "index_advice").at(-1).args);
assert.deepEqual([call.id, call.db], [1, "shop"]);
assert.equal(await page.locator("input[aria-label='Fix idx_c on orders']").isChecked(), true);
assert.equal(await page.locator("input[aria-label='Fix idx_s2 on orders']").isChecked(), true);
assert.equal(await page.locator("input[aria-label='Fix fk_order on items']").isChecked(), false, "adding an index is a choice, not a default");
assert.match(await page.locator("h3:has-text('Unused') + p, h3:has-text('Unused') ~ p").first().innerText(), /since the server started/);
assert.ok(await page.locator("table[aria-label='Unused indexes']").innerText().then((t) => t.includes("idx_old")));
ok("findings are listed with their reasons; drops are pre-selected, the missing foreign key index is not; unused indexes are shown");

await page.click("button:has-text('Preview and apply')");
await page.waitForSelector("text=Index changes: shop");
const dlg = await page.locator(".dialog").innerText();
assert.ok(dlg.includes("DROP INDEX `idx_c` ON `shop`.`orders`") && dlg.includes("DROP INDEX `idx_s2`") && !dlg.includes("CREATE INDEX"), dlg);
ok("Preview SQL shows exactly the chosen statements");
await page.click(".dialog button:has-text('Apply changes')");
await page.waitForFunction(() => window.__calls.some((c) => c.cmd === "run_plan"));
const ran = await page.evaluate(() => window.__calls.filter((c) => c.cmd === "run_plan").at(-1).args);
assert.deepEqual(ran.statements.filter((s) => s.startsWith("DROP")).length, 2);
ok("applying runs them on the connection");
assert.deepEqual(errors, []);
await browser.close();
console.log("ALL INDEX ADVISOR UI CHECKS PASSED");
